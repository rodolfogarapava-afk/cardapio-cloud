export function getRestaurantBySlug(slug: string): Restaurant | undefined {
  return mockRestaurants.find(r => r.slug === slug);
}

export function getCategoriesBySlug(slug: string): ProductCategory[] {
  return mockCategories[slug] || [];
}

export function getProductsBySlug(slug: string): Product[] {
  return mockMenuProducts[slug] || [];
}

export function getProductsByCategory(slug: string, categoryId: string): Product[] {
  const products = mockMenuProducts[slug] || [];
  return products.filter(p => p.categoryId === categoryId);
}
